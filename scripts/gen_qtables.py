"""Generate breezetoken/quant/_tables.py from ggml-common.h.

The IQ dequantization grids are data ported from llama.cpp's ggml (MIT).
Regenerate after upgrading the vendored reference with::

    uv run python scripts/gen_qtables.py /path/to/ggml-common.h

The generated arrays are little-endian unpackings of the C hex tables:

* ``iq2s_grid``   -- (1024, 8) int8,  grid rows selected by 8 index bits + 2 qh bits
* ``iq3s_grid``   -- ( 512, 4) int8,  grid rows selected by 8 index bits + 1 qh bit
* ``kvalues_iq4nl`` -- (16,) int8
* ``kmask_iq2xs`` -- (8,) uint8, sign bit selectors
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def extract_table(header: Path, name: str) -> list[int]:
    text = header.read_text()
    match = re.search(
        rf"GGML_TABLE_BEGIN\([^,]+,\s*{name},\s*\d+\)\s*(.*?)GGML_TABLE_END\(\)",
        text,
        re.S,
    )
    if not match:
        raise SystemExit(f"table {name} not found in {header}")
    body = match.group(1)
    values: list[int] = []
    for token in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body):
        values.append(int(token, 0))
    return values


def unpack_rows(values: list[int], row_bits: int) -> list[list[int]]:
    """Split packed integers into little-endian signed-byte rows."""
    per_row = row_bits // 8
    mask = (1 << row_bits) - 1
    rows = []
    for value in values:
        value &= mask
        row = []
        for i in range(per_row):
            byte = (value >> (8 * i)) & 0xFF
            row.append(byte - 256 if byte >= 128 else byte)
        rows.append(row)
    return rows


def main() -> None:
    header = Path(
        sys.argv[1] if len(sys.argv) > 1 else "/home/xun/projects/llama.cpp/ggml/src/ggml-common.h"
    )
    out = Path(__file__).resolve().parent.parent / "breezetoken" / "quant" / "_tables.py"

    iq2s = unpack_rows(extract_table(header, "iq2s_grid"), 64)
    iq3s = unpack_rows(extract_table(header, "iq3s_grid"), 32)
    iq4nl = extract_table(header, "kvalues_iq4nl")
    kmask = extract_table(header, "kmask_iq2xs")

    assert len(iq2s) == 1024 and len(iq2s[0]) == 8, len(iq2s)
    assert len(iq3s) == 512 and len(iq3s[0]) == 4, len(iq3s)
    assert iq4nl == [-127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113]
    assert kmask == [1, 2, 4, 8, 16, 32, 64, 128]

    def fmt(rows) -> str:
        return "[" + ",\n    ".join(str(r) for r in rows) + "]"

    out.write_text(
        '"""Lookup tables for IQ dequantization, ported from ggml (MIT).\n'
        "\n"
        "Generated by scripts/gen_qtables.py from ggml-common.h; do not edit.\n"
        '"""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "import numpy as np\n"
        "\n"
        "#: (1024, 8) int8 -- iq2_s grid, index = 8 qs bits | 2 qh bits\n"
        f"IQ2S_GRID = np.array({fmt(iq2s)}, dtype=np.int8)\n"
        "\n"
        "#: (512, 4) int8 -- iq3_s grid, index = 8 qs bits | 1 qh bit\n"
        f"IQ3S_GRID = np.array({fmt(iq3s)}, dtype=np.int8)\n"
        "\n"
        "#: (16,) int8 -- iq4_xs non-linear values\n"
        f"IQ4NL_VALUES = np.array({iq4nl}, dtype=np.int8)\n"
        "\n"
        "#: (8,) uint8 -- bit selectors for the packed IQ sign bytes\n"
        f"IQ_SIGN_MASK = np.array({kmask}, dtype=np.uint8)\n"
    )
    print(f"wrote {out} ({len(iq2s)} iq2s rows, {len(iq3s)} iq3s rows)")


if __name__ == "__main__":
    main()
